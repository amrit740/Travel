  /**
   * Retrieves places for a destination across all categories
   */
  public static getPlacesForDestination(
    destinationQuery?: string,
    categoryFilter?: string,
    searchQuery?: string
  ): Place[] {
    const allPlaces = [...MASTER_INDIA_PLACES];

    // If a specific destination was requested, find or generate structured places for it
    let targetPlaces: Place[] = [];
    const destClean = destinationQuery?.trim().toLowerCase() || '';

    if (!destClean || destClean === 'all' || destClean === 'india') {
      targetPlaces = allPlaces;
    } else {
      // 1. Direct match in master catalog
      const directMatches = allPlaces.filter((p) => {
        const pDest = p.destination.toLowerCase();
        return pDest.includes(destClean) || destClean.includes(pDest);
      });

      if (directMatches.length > 0) {
        targetPlaces = directMatches;
      } else {
        // 2. Lookup state / regional knowledge base
        const dynamicStatePlaces = this.generatePlacesFromStateKnowledge(destinationQuery!);
        targetPlaces = dynamicStatePlaces;
      }
    }

    // Ensure we have places across all 4 categories (Attraction, Restaurant, Hotel, Hidden Gem)
    // If any category is missing for this destination, dynamically backfill authentic real items
    if (destinationQuery && targetPlaces.length > 0) {
      targetPlaces = this.ensureAllCategoriesPopulated(destinationQuery, targetPlaces);
    }

    // Apply Category Filter
    let filtered = targetPlaces;
    if (categoryFilter && categoryFilter !== 'All') {
      const catLower = categoryFilter.toLowerCase();
      filtered = filtered.filter((p) => {
        if (catLower === 'attraction' || catLower === 'sights & monuments' || catLower === 'sightseeing') {
          return p.category === 'Attraction';
        }
        if (catLower === 'restaurant' || catLower === 'dining & cafes' || catLower === 'food') {
          return p.category === 'Restaurant';
        }
        if (catLower === 'hotel' || catLower === 'stays & resorts' || catLower === 'stay') {
          return p.category === 'Hotel';
        }
        if (catLower === 'hidden gem' || catLower === 'hidden gems' || catLower === 'offbeat') {
          return p.category === 'Hidden Gem';
        }
        return p.category.toLowerCase() === catLower;
      });
    }

    // Apply Keyword Search Filter
    if (searchQuery && searchQuery.trim()) {
      const q = searchQuery.toLowerCase().trim();
      filtered = filtered.filter((p) => {
        return (
          p.name.toLowerCase().includes(q) ||
          p.description.toLowerCase().includes(q) ||
          p.sub_category?.toLowerCase().includes(q) ||
          p.destination.toLowerCase().includes(q) ||
          p.address?.toLowerCase().includes(q) ||
          p.tags.some((t) => t.toLowerCase().includes(q)) ||
          // Support searching terms like "coffee", "fort", "hotel", "waterfall", "vegetarian", "hidden"
          (q === 'coffee' && (p.tags.includes('Coffee') || p.category === 'Restaurant')) ||
          (q === 'fort' && (p.tags.includes('Fort') || p.name.toLowerCase().includes('fort'))) ||
          (q === 'hotel' && p.category === 'Hotel') ||
          (q === 'waterfall' && (p.tags.includes('Waterfall') || p.name.toLowerCase().includes('waterfall'))) ||
          (q === 'vegetarian' && (p.tags.includes('Vegetarian') || p.tags.includes('Vegetarian-Friendly'))) ||
          (q === 'hidden' && p.category === 'Hidden Gem')
        );
      });
    }

    return filtered;
  }

