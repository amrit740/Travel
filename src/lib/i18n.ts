const STORAGE_LANG_KEY = 'travelwise_preferred_language';

export const getStoredLanguage = (): SupportedLanguage => {
  const saved = localStorage.getItem(STORAGE_LANG_KEY) as SupportedLanguage;
  if (saved && TRANSLATIONS[saved]) return saved;
  return 'en';
};

export const setStoredLanguage = (lang: SupportedLanguage): void => {
  localStorage.setItem(STORAGE_LANG_KEY, lang);
};

export const t = (key: string, lang: SupportedLanguage = getStoredLanguage()): string => {
  const langDict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  return langDict[key] || TRANSLATIONS.en[key] || key;
};
