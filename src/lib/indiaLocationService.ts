/**
 * Intelligent Multi-Tier Search for India:
 * Matches cities, states, attractions, themes, keywords, and natural language queries.
 */
export function searchIndianLocations(query: string): IndianLocationResult[] {
  if (!query || !query.trim()) {
    return CORE_INDIAN_DESTINATIONS;
  }

  const rawQ = query.trim();
  const q = rawQ.toLowerCase();

  // Strict check: If user typed international keyword, return zero results
  if (!isIndianLocation(rawQ)) {
    return [];
  }

  const results: Array<{ item: IndianLocationResult; score: number }> = [];

  // Match against Core Curated Destinations
  for (const loc of CORE_INDIAN_DESTINATIONS) {
    let score = 0;
    const name = loc.name.toLowerCase();
    const state = loc.state.toLowerCase();
    const city = loc.district_or_city.toLowerCase();
    const desc = loc.description.toLowerCase();
    const cat = loc.category.toLowerCase();
    const themes = loc.travel_themes.map((t) => t.toLowerCase());
    const activities = loc.activities.map((a) => a.toLowerCase());

    if (name === q) score += 100;
    else if (name.startsWith(q)) score += 80;
    else if (name.includes(q)) score += 50;

    if (state.includes(q)) score += 40;
    if (city.includes(q)) score += 40;
    if (cat.includes(q)) score += 30;

    // Natural queries: e.g. "forts in maharashtra", "beaches in goa", "places near gangtok"
    const words = q.split(/\s+/).filter((w) => !['in', 'near', 'from', 'to', 'the', 'best', 'places', 'trips', 'trip', 'weekend'].includes(w));
    let matchedWords = 0;
    for (const w of words) {
      if (
        name.includes(w) ||
        state.includes(w) ||
        city.includes(w) ||
        desc.includes(w) ||
        cat.includes(w) ||
        themes.some((t) => t.includes(w)) ||
        activities.some((a) => a.includes(w))
      ) {
        matchedWords++;
      }
    }
    if (words.length > 0 && matchedWords === words.length) {
      score += 45 * matchedWords;
    }

    if (score > 0) {
      results.push({ item: loc, score });
    }
  }

  // Also match dynamically against all 28 States dataset
  for (const stateObj of ALL_INDIA_STATES) {
    const sName = stateObj.name.toLowerCase();
    const sDesc = stateObj.description.toLowerCase();
    const sCap = stateObj.capital.toLowerCase();

    // Check if query is targeting this state or its destinations
    for (const dest of stateObj.destinations) {
      const dName = dest.name.toLowerCase();
      const dCity = dest.city_district.toLowerCase();
      const dType = dest.type.toLowerCase();
      const dDesc = dest.description.toLowerCase();

      // Check if already in results
      const alreadyIn = results.some(
        (r) => r.item.name.toLowerCase() === dName || r.item.id === `state-dest-${dest.id}`
      );
      if (alreadyIn) continue;

      let score = 0;
      if (dName === q) score += 95;
      else if (dName.startsWith(q)) score += 75;
      else if (dName.includes(q)) score += 45;

      if (sName.includes(q) || dCity.includes(q)) score += 35;
      if (dType.includes(q)) score += 25;

      const words = q.split(/\s+/).filter((w) => !['in', 'near', 'from', 'to', 'the', 'best', 'places', 'trips', 'trip'].includes(w));
      let matchedWords = 0;
      for (const w of words) {
        if (dName.includes(w) || sName.includes(w) || dCity.includes(w) || dType.includes(w) || dDesc.includes(w)) {
          matchedWords++;
        }
      }
      if (words.length > 0 && matchedWords === words.length) {
        score += 35 * matchedWords;
      }

      if (score > 0) {
        results.push({
          score,
          item: {
            id: `state-dest-${dest.id}`,
            name: dest.name,
            state: stateObj.name,
            district_or_city: dest.city_district,
            country: 'India',
            description: dest.description,
            category: (dest.type as any) || 'Historical & Heritage',
            subcategory: `${dest.type} in ${stateObj.name}`,
            latitude: dest.latitude,
            longitude: dest.longitude,
            best_time_to_visit: dest.best_time || stateObj.best_seasons,
            recommended_duration: dest.recommended_duration || '2 - 3 Days',
            budget_category: dest.budget_category || 'Mid-range',
            travel_themes: stateObj.popular_themes,
            activities: dest.attractions.map((a) => a.name),
            accessibility: dest.accessibility,
            nearby_destinations: stateObj.destinations.filter((d) => d.id !== dest.id).slice(0, 4).map((d) => d.name),
            image: dest.image || stateObj.cover_image,
          },
        });
      }
    }
  }

  // Sort by match score descending
  results.sort((a, b) => b.score - a.score);

  return results.map((r) => r.item);
}

/**
 * Fast Autocomplete Suggester for Search Inputs across India
 */
export function getIndianLocationSuggestions(query: string, limit: number = 8): Array<{
  id: string;
  name: string;
  subtitle: string;
  category: string;
  state: string;
}> {
  if (!query || !query.trim() || !isIndianLocation(query)) {
    return [];
  }

  const matches = searchIndianLocations(query);
  return matches.slice(0, limit).map((m) => ({
    id: m.id,
    name: m.name,
    subtitle: `${m.district_or_city}, ${m.state}`,
    category: m.category,
    state: m.state,
  }));
}
