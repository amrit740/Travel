/**
 * Validates if a location name, query string, or coords belong strictly to India.
 */
export function isIndianLocation(queryOrName: string, lat?: number, lng?: number): boolean {
  if (!queryOrName || !queryOrName.trim()) return false;
  const q = queryOrName.toLowerCase().trim();

  // Explicit check against international keywords
  for (const intl of KNOWN_INTERNATIONAL_KEYWORDS) {
    // If the query exactly matches or contains international keyword as a discrete word
    const regex = new RegExp(`\\b${intl}\\b`, 'i');
    if (regex.test(q)) {
      return false;
    }
  }

  // If geographic coordinates are provided, verify they fall within India bounding box
  // Lat: ~6.0° N to 38.0° N, Long: ~68.0° E to 98.0° E
  if (typeof lat === 'number' && typeof lng === 'number' && !isNaN(lat) && !isNaN(lng)) {
    const isWithinIndiaBox = lat >= 6.0 && lat <= 38.5 && lng >= 68.0 && lng <= 98.5;
    if (!isWithinIndiaBox) return false;
  }

  return true;
}

